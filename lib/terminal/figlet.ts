export const FIGLET_ROWS = 6;

/** Render `text` as six rows of block letters. Unknown characters are skipped. */
export function figlet(text: string): string[] {
  const rows: string[] = Array.from({ length: FIGLET_ROWS }, () => "");
  for (const ch of text.toUpperCase()) {
    const g = GLYPHS[ch];
    if (!g) continue;
    const width = Math.max(...g.map((r) => r.length));
    for (let i = 0; i < FIGLET_ROWS; i++) rows[i] += (g[i] ?? "").padEnd(width) + " ";
  }
  return rows.map((r) => r.trimEnd());
}
